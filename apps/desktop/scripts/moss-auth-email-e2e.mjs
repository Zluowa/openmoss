function parseOptions(argv, env) {
  const cli = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") return { help: true };
    if (arg === "--remove-secondary") {
      cli.removeSecondary = true;
      continue;
    }
    const next = argv[index + 1];
    if (!next || next.startsWith("--")) throw new Error("missing option value");
    const optionByFlag = {
      "--app-url": "appUrl",
      "--cdp-url": "cdpUrl",
      "--dev-url": "appUrl",
      "--email": "email",
      "--email-domain": "emailDomain",
      "--inbucket-api": "inbucketApi",
      "--mail-timeout-ms": "mailTimeoutMs",
      "--mailpit-api": "mailpitApi",
      "--poll-ms": "pollMs",
      "--second-email": "secondEmail",
      "--timeout-ms": "timeoutMs",
    };
    const key = optionByFlag[arg];
    if (!key) throw new Error("unknown option");
    cli[key] = next;
    index += 1;
  }

  const emailDomain = cli.emailDomain ?? env.MOSS_AUTH_E2E_EMAIL_DOMAIN ?? "example.test";
  if (!/^[a-z0-9.-]+$/i.test(emailDomain) || !emailDomain.includes(".")) {
    throw new Error("invalid email domain");
  }
  const email = String(cli.email ?? env.MOSS_AUTH_E2E_EMAIL ?? generatedEmail(emailDomain))
    .trim()
    .toLowerCase();
  if (!EMAIL_PATTERN.test(email)) throw new Error("invalid email");

  const secondEmailValue = cli.secondEmail ?? env.MOSS_AUTH_E2E_SECOND_EMAIL;
  const secondEmail = secondEmailValue ? String(secondEmailValue).trim().toLowerCase() : null;
  if (secondEmail && !EMAIL_PATTERN.test(secondEmail)) throw new Error("invalid second email");

  const mailpitValue = cli.mailpitApi ?? env.MOSS_AUTH_E2E_MAILPIT_API;
  const explicitlyConfiguredInbucket = cli.inbucketApi ?? env.MOSS_AUTH_E2E_INBUCKET_API;
  if (mailpitValue && explicitlyConfiguredInbucket) throw new Error("choose one mail API");

  const password = env.MOSS_AUTH_E2E_PASSWORD || generatedPassword();
  let newPassword = env.MOSS_AUTH_E2E_NEW_PASSWORD || generatedPassword();
  if (newPassword === password) newPassword = generatedPassword();
  if (password.length < 8 || newPassword.length < 8) throw new Error("password too short");

  return {
    help: false,
    appUrl: cleanUrl(
      cli.appUrl ?? env.MOSS_AUTH_E2E_APP_URL ?? env.MOSS_AUTH_E2E_DEV_URL ?? DEFAULT_APP_URL,
      ["http:", "https:", "moss:"],
    ),
    cdpUrl: cleanUrl(
      cli.cdpUrl ?? env.MOSS_AUTH_E2E_CDP_URL ?? DEFAULT_CDP_URL,
      ["http:", "https:", "ws:", "wss:"],
      { loopbackOnly: true },
    ),
    email,
    inbucketApi: mailpitValue
      ? null
      : cleanUrl(explicitlyConfiguredInbucket ?? DEFAULT_INBUCKET_API, ["http:", "https:"], {
          stripApiSuffix: true,
        }),
    mailpitApi: mailpitValue
      ? cleanUrl(mailpitValue, ["http:", "https:"], { stripApiSuffix: true })
      : null,
    mailTimeoutMs: readPositiveInteger(
      cli.mailTimeoutMs ?? env.MOSS_AUTH_E2E_MAIL_TIMEOUT_MS,
      DEFAULT_MAIL_TIMEOUT_MS,
    ),
    newPassword,
    password,
    pollMs: Math.min(
      5_000,
      readPositiveInteger(cli.pollMs ?? env.MOSS_AUTH_E2E_POLL_MS, DEFAULT_POLL_MS),
    ),
    removeSecondary:
      cli.removeSecondary === true ||
      /^(?:1|true)$/i.test(env.MOSS_AUTH_E2E_REMOVE_SECONDARY ?? ""),
    secondEmail,
    secondPassword: env.MOSS_AUTH_E2E_SECOND_PASSWORD || null,
    timeoutMs: readPositiveInteger(
      cli.timeoutMs ?? env.MOSS_AUTH_E2E_TIMEOUT_MS,
      DEFAULT_TIMEOUT_MS,
    ),
  };
}

async function runStep(name, operation) {
  activeStep = name;
  printStatus("RUN", name);
  const result = await operation();
  printStatus("PASS", name);
  return result;
}

function sleep(durationMs) {
  return new Promise((resolveWait) => setTimeout(resolveWait, durationMs));
}

async function fetchJson(url, timeoutMs, { allowNotFound = false } = {}) {
  const response = await fetch(url, {
    headers: { accept: "application/json" },
    redirect: "error",
    signal: AbortSignal.timeout(timeoutMs),
  });
  if (allowNotFound && response.status === 404) return null;
  if (!response.ok) throw new Error("mail API request failed");
  return response.json();
}

function listPayloadMessages(payload) {
  if (Array.isArray(payload)) return payload;
  if (!payload || typeof payload !== "object") return [];
  for (const key of ["messages", "Messages", "items", "Items"]) {
    if (Array.isArray(payload[key])) return payload[key];
  }
  return [];
}

function createMailpitClient(baseUrl, timeoutMs) {
  return {
    async list(email) {
      const url = new URL(`${baseUrl}/api/v1/search`);
      url.searchParams.set("query", `to:${email}`);
      return listPayloadMessages(await fetchJson(url, timeoutMs));
    },
    async read(_email, summary) {
      const id = messageIdentity(summary);
      if (!id) return summary;
      const url = new URL(`${baseUrl}/api/v1/message/${encodeURIComponent(id)}`);
      return (await fetchJson(url, timeoutMs, { allowNotFound: true })) ?? summary;
    },
  };
}

function inbucketMailboxCandidates(email) {
  const localPart = email.slice(0, email.lastIndexOf("@"));
  return [...new Set([email, localPart])];
}

function createInbucketClient(baseUrl, timeoutMs) {
  return {
    async list(email) {
      for (const mailbox of inbucketMailboxCandidates(email)) {
        const url = new URL(`${baseUrl}/api/v1/mailbox/${encodeURIComponent(mailbox)}`);
        const payload = await fetchJson(url, timeoutMs, { allowNotFound: true });
        const messages = listPayloadMessages(payload);
        if (messages.length > 0) {
          for (const entry of messages) {
            if (entry && typeof entry === "object") entry.__mailbox = mailbox;
          }
          return messages;
        }
      }
      return [];
    },
    async read(email, summary) {
      const id = messageIdentity(summary);
      if (!id) return summary;
      const mailbox = summary.__mailbox ?? inbucketMailboxCandidates(email)[0];
      const url = new URL(
        `${baseUrl}/api/v1/mailbox/${encodeURIComponent(mailbox)}/${encodeURIComponent(id)}`,
      );
      return (await fetchJson(url, timeoutMs, { allowNotFound: true })) ?? summary;
    },
  };
}

async function waitForAuthMail(client, email, expectedKind, options) {
  const deadline = Date.now() + options.mailTimeoutMs;
  while (Date.now() < deadline) {
    const summaries = await client.list(email);
    for (const summary of summaries.toReversed()) {
      const detail = await client.read(email, summary);
      const subject = messageSubject(detail) || messageSubject(summary);
      const content = `${messageContent(summary)}\n${messageContent(detail)}`;
      if (classifyAuthMail({ subject, content }) !== expectedKind) continue;
      const actionLink = extractAuthActionLink(content);
      if (actionLink) return actionLink;
    }
    await sleep(options.pollMs);
  }
  throw new Error("auth mail did not arrive");
}

async function followAuthActionToCode(actionLink, timeoutMs) {
  let current = actionLink;
  for (let redirectCount = 0; redirectCount < 6; redirectCount += 1) {
    const parsed = new URL(current);
    if (parsed.protocol === "moss:") {
      const code = extractMossAuthCode(current);
      if (!code) throw new Error("invalid Moss callback");
      return code;
    }
    if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
      throw new Error("invalid auth action protocol");
    }
    if (parsed.protocol === "http:" && !isLoopbackHost(parsed.hostname)) {
      throw new Error("plain HTTP auth action must be loopback");
    }
    const response = await fetch(current, {
      redirect: "manual",
      signal: AbortSignal.timeout(timeoutMs),
    });
    const location = response.headers.get("location");
    if (!location || response.status < 300 || response.status >= 400) {
      throw new Error("auth action did not redirect");
    }
    current = new URL(location, current).toString();
  }
  throw new Error("too many auth redirects");
}

function packageRequire(packageJsonPath) {
  return createRequire(resolve(REPO_ROOT, packageJsonPath));
}

async function importChromium() {
  const requireFromWeb = packageRequire("apps/web/package.json");
  const moduleUrl = pathToFileURL(requireFromWeb.resolve("playwright", { paths: [WEB_ROOT] })).href;
  const playwright = await import(moduleUrl);
  const chromium = playwright.chromium ?? playwright.default?.chromium;
  if (!chromium) throw new Error("Playwright Chromium unavailable");
  return chromium;
}

function appPageMatches(pageUrl, appUrl) {
  try {
    const page = new URL(pageUrl);
    const app = new URL(appUrl);
    return (
      page.protocol === app.protocol &&
      page.hostname === app.hostname &&
      page.port === app.port &&
      page.pathname === app.pathname
    );
  } catch {
    return false;
  }
}

async function connectToExistingPage(options) {
  const chromium = await importChromium();
  const browser = await chromium.connectOverCDP(options.cdpUrl, { timeout: options.timeoutMs });
  const pages = browser.contexts().flatMap((context) => context.pages());
  const page = pages.find((candidate) => appPageMatches(candidate.url(), options.appUrl));
  if (!page) throw new Error("matching Electron page unavailable");
  const isElectron = await page.evaluate(() => /\bElectron\/\d/i.test(navigator.userAgent));
  if (!isElectron) throw new Error("CDP target is not Electron");
  page.setDefaultTimeout(options.timeoutMs);
  page.setDefaultNavigationTimeout(options.timeoutMs);
  return page;
}

async function gotoRoute(page, options, route, search = {}) {
  await page.goto(buildAppHashRoute(options.appUrl, route, search), {
    waitUntil: "domcontentloaded",
  });
  await page.waitForFunction((path) => window.location.hash.startsWith(`#${path}`), route);
}

async function openTransientHashRoute(page, options, route, search) {
  const targetHash = new URL(buildAppHashRoute(options.appUrl, route, search)).hash;
  await page
    .evaluate((hash) => {
      window.location.hash = hash;
    }, targetHash)
    .catch(() => {
      // Fast auth redirects can replace the execution context before Playwright
      // receives the evaluate result. The destination assertion remains authoritative.
    });
}

async function waitForAccount(page) {
  await page.waitForFunction(() => window.location.hash.startsWith("#/account"));
  printStatus("INFO", "account-route-ready");
  await page.getByRole("button", { name: "Sign out", exact: true }).waitFor({ state: "visible" });
  printStatus("INFO", "account-session-ready");
  await page
    .getByText(/^Verified(?:\s*·|$)/)
    .first()
    .waitFor({ state: "visible" });
  printStatus("INFO", "account-verification-ready");
}

async function signOut(page, options) {
  await page.getByRole("button", { name: "Sign out", exact: true }).click();

  await page.waitForFunction(() => {
    if (window.location.hash.startsWith("#/login")) {
      return Boolean(document.querySelector("#moss-login-email"));
    }
    if (!window.location.hash.startsWith("#/account")) return false;

    const heading = document.querySelector("#moss-account-heading")?.textContent?.trim();
    const savedAccountsHeading = document
      .querySelector("#saved-accounts-heading")
      ?.textContent?.trim();
    const stillSignedIn = [...document.querySelectorAll("button")].some(
      (button) => button.textContent?.trim() === "Sign out",
    );
    return (
      heading === "Your accounts" && savedAccountsHeading === "Saved accounts" && !stillSignedIn
    );
  });

  await gotoRoute(page, options, "/login");
  await page.getByRole("heading", { name: "Sign in to Moss", exact: true }).waitFor({
    state: "visible",
  });
  await page.locator("#moss-login-email").waitFor({ state: "visible" });
}

async function enterLoginEmail(page, email) {
  const emailInput = page.locator("#moss-login-email");
  await emailInput.waitFor({ state: "visible" });
  await emailInput.fill(email);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.locator("#moss-login-password").waitFor({ state: "visible" });
}

async function submitLoginPassword(page, password) {
  await page.locator("#moss-login-password").fill(password);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
}

async function waitForSavedAccountState(page, email, current) {
  await page.waitForFunction(
    ({ accessibleName, shouldBeCurrent }) => {
      const control = [...document.querySelectorAll("button, a")].find(
        (element) => element.getAttribute("aria-label") === accessibleName,
      );
      if (!control) return false;
      const disabled = control instanceof HTMLButtonElement && control.disabled;
      const label = control.textContent?.trim() ?? "";
      return shouldBeCurrent
        ? disabled && label === "Current"
        : control instanceof HTMLButtonElement && !disabled && label === "Use";
    },
    { accessibleName: `Use ${email}`, shouldBeCurrent: current },
  );
}

async function runOptionalMultiAccount(page, options) {
  const addAccount = page.getByRole("link", { name: "Add account", exact: true });
  if ((await addAccount.count()) === 0) {
    printStatus("SKIP", "multi-account-ui-not-present");
    return;
  }

  await runStep("multi-account-add-mode", async () => {
    await addAccount.click();
    await page.waitForFunction(() => {
      const add = new URLSearchParams(window.location.hash.split("?")[1] ?? "").get("add");
      return window.location.hash.startsWith("#/login") && (add === "true" || add === "1");
    });
    await page.getByRole("heading", { name: "Add a Moss account", exact: true }).waitFor({
      state: "visible",
    });
    await page.locator("#moss-login-email").waitFor({ state: "visible" });
  });

  if (!options.secondEmail || !options.secondPassword) {
    printStatus("SKIP", "multi-account-switch-no-secondary-credentials");
    await gotoRoute(page, options, "/account");
    await waitForAccount(page);
    return;
  }

  await runStep("multi-account-add-secondary", async () => {
    await enterLoginEmail(page, options.secondEmail);
    await submitLoginPassword(page, options.secondPassword);
    await waitForAccount(page);
    await page.getByText("Saved accounts", { exact: true }).waitFor({ state: "visible" });
    await waitForSavedAccountState(page, options.email, false);
    await waitForSavedAccountState(page, options.secondEmail, true);
  });

  await runStep("multi-account-switch-primary", async () => {
    await page.getByRole("button", { name: `Use ${options.email}`, exact: true }).click();
    await waitForSavedAccountState(page, options.email, true);
    await waitForSavedAccountState(page, options.secondEmail, false);
  });

  if (options.removeSecondary) {
    const removeSecondary = page.getByRole("button", {
      name: `Remove ${options.secondEmail}`,
      exact: true,
    });
    await runStep("multi-account-remove-secondary", async () => {
      await removeSecondary.waitFor({ state: "visible" });
      await removeSecondary.click();
      await page
        .getByRole("button", { name: `Remove ${options.secondEmail}`, exact: true })
        .waitFor({ state: "detached" });
    });
  }
}

async function clearSensitiveRoute() {
  if (!connectedPage || !appUrlForCleanup) return;
  try {
    const current = connectedPage.url();
    if (!/[?&]code=/.test(current)) return;
    await connectedPage.goto(buildAppHashRoute(appUrlForCleanup, "/login"), {
      waitUntil: "domcontentloaded",
      timeout: 5_000,
    });
  } catch {
    // Best-effort only. Never print a URL or browser error because it may contain a code.
  }
}

async function exitAfterCleanup(code) {
  if (exiting) return;
  exiting = true;
  await clearSensitiveRoute();
  // Do not call browser.close(): this script connected to a user-owned Electron process.
  process.exit(code);
}

for (const signal of ["SIGINT", "SIGTERM"]) {
  process.once(signal, () => {
    printStatus("FAIL", "interrupted");
    void exitAfterCleanup(signal === "SIGINT" ? 130 : 143);
  });
}

async function run() {
  const options = parseOptions(process.argv.slice(2), process.env);
  if (options.help) {
    printHelp();
    return;
  }

  printStatus("INFO", "synthetic-account", maskEmail(options.email));
  const mailClient = options.mailpitApi
    ? createMailpitClient(options.mailpitApi, options.timeoutMs)
    : createInbucketClient(options.inbucketApi, options.timeoutMs);

  const page = await runStep("connect-existing-electron", () => connectToExistingPage(options));
  connectedPage = page;
  appUrlForCleanup = options.appUrl;

  await runStep("prepare-signed-out", async () => {
    await gotoRoute(page, options, "/account");
    const signOutButton = page.getByRole("button", { name: "Sign out", exact: true });
    if (await signOutButton.isVisible().catch(() => false)) {
      await signOut(page, options);
    }
  });

  await runStep("signup", async () => {
    await gotoRoute(page, options, "/signup");
    await page.locator("#moss-signup-name").waitFor({ state: "visible" });
    await page.locator("#moss-signup-name").fill("Moss E2E");
    await page.locator("#moss-signup-email").fill(options.email);
    await page.locator("#moss-signup-password").fill(options.password);
    await page.getByRole("button", { name: "Create account", exact: true }).click();
    await page.waitForFunction(() => window.location.hash.startsWith("#/verify-email"));
    await page.getByText("Check your email", { exact: true }).waitFor({ state: "visible" });
  });

  const signupActionLink = await runStep("receive-signup-email", () =>
    waitForAuthMail(mailClient, options.email, "signup", options),
  );
  const signupCode = await runStep("follow-signup-email-to-moss-code", () =>
    followAuthActionToCode(signupActionLink, options.timeoutMs),
  );

  await runStep("verify-signup-callback", async () => {
    await openTransientHashRoute(page, options, "/auth/callback", { code: signupCode });
    await waitForAccount(page);
  });

  await runStep("logout-after-signup", () => signOut(page, options));

  await runStep("reject-wrong-password", async () => {
    await enterLoginEmail(page, options.email);
    await submitLoginPassword(page, generatedPassword());
    await page.getByRole("alert").waitFor({ state: "visible" });
    await page.getByText("Email or password is incorrect.", { exact: true }).waitFor({
      state: "visible",
    });
  });

  await runStep("accept-correct-password", async () => {
    await submitLoginPassword(page, options.password);
    await waitForAccount(page);
  });

  await runStep("logout-before-recovery", () => signOut(page, options));

  await runStep("request-password-reset", async () => {
    await enterLoginEmail(page, options.email);
    await page.getByRole("link", { name: "Forgot password?", exact: true }).click();
    await page.locator("#moss-forgot-email").waitFor({ state: "visible" });
    await page.locator("#moss-forgot-email").fill(options.email);
    await page.getByRole("button", { name: "Send reset link", exact: true }).click();
    await page.getByText("Check your email", { exact: true }).waitFor({ state: "visible" });
  });

  const recoveryActionLink = await runStep("receive-password-reset-email", () =>
    waitForAuthMail(mailClient, options.email, "recovery", options),
  );
  const recoveryCode = await runStep("follow-reset-email-to-moss-code", () =>
    followAuthActionToCode(recoveryActionLink, options.timeoutMs),
  );

  await runStep("open-recovery-callback", async () => {
    await openTransientHashRoute(page, options, "/auth/callback", { code: recoveryCode });
    await page.waitForFunction(() => window.location.hash.startsWith("#/reset-password"));
    await page.locator("#moss-reset-password").waitFor({ state: "visible" });
  });

  await runStep("update-password", async () => {
    await page.locator("#moss-reset-password").fill(options.newPassword);
    await page.locator("#moss-reset-confirm-password").fill(options.newPassword);
    await page.getByRole("button", { name: "Update password", exact: true }).click();
    await waitForAccount(page);
  });

  await runStep("logout-after-password-update", () => signOut(page, options));

  await runStep("reject-old-password", async () => {
    await enterLoginEmail(page, options.email);
    await submitLoginPassword(page, options.password);
    await page.getByText("Email or password is incorrect.", { exact: true }).waitFor({
      state: "visible",
    });
  });

  await runStep("accept-new-password", async () => {
    await submitLoginPassword(page, options.newPassword);
    await waitForAccount(page);
  });

  await runOptionalMultiAccount(page, options);

  await runStep("final-logout", () => signOut(page, options));
  printStatus("PASS", "complete");
}

