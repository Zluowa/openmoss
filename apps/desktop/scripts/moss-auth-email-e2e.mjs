const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..", "..", "..");
const WEB_ROOT = resolve(REPO_ROOT, "apps", "web");

const DEFAULT_CDP_URL = "http://127.0.0.1:9230";
const DEFAULT_APP_URL = "http://localhost:5733";
const DEFAULT_INBUCKET_API = "http://127.0.0.1:54324";
const DEFAULT_TIMEOUT_MS = 30_000;
const DEFAULT_MAIL_TIMEOUT_MS = 60_000;
const DEFAULT_POLL_MS = 500;
const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

let activeStep = "configuration";
let connectedPage = null;
let appUrlForCleanup = null;
let exiting = false;

function isLoopbackHost(hostname) {
  const host = hostname.replace(/^\[|\]$/g, "");
  return new Set(["localhost", "127.0.0.1", "::1"]).has(host);
}

function printStatus(kind, step, detail = "") {
  process.stderr.write(`[moss-auth-e2e] ${kind} ${step}${detail ? ` ${detail}` : ""}\n`);
}

function generatedPassword() {
  return `Moss!${randomBytes(18).toString("base64url")}aA9`;
}

function generatedEmail(domain) {
  const timestamp = Date.now().toString(36);
  const suffix = randomBytes(5).toString("hex");
  return `moss-e2e-${timestamp}-${suffix}@${domain}`;
}

function readPositiveInteger(value, fallback) {
  if (value === undefined || value === null || String(value).trim() === "") return fallback;
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed <= 0) throw new Error("invalid numeric option");
  return parsed;
}

function cleanUrl(value, protocols, { loopbackOnly = false, stripApiSuffix = false } = {}) {
  const parsed = new URL(value);
  if (!protocols.includes(parsed.protocol) || parsed.username || parsed.password || parsed.search) {
    throw new Error("invalid endpoint");
  }
  if (loopbackOnly) {
    if (!isLoopbackHost(parsed.hostname)) {
      throw new Error("endpoint must be loopback");
    }
  }
  if (parsed.protocol === "http:" && !isLoopbackHost(parsed.hostname)) {
    throw new Error("plain HTTP endpoint must be loopback");
  }
  parsed.hash = "";
  let normalized = parsed.toString().replace(/\/$/, "");
  if (stripApiSuffix) normalized = normalized.replace(/\/api\/v1$/i, "");
  return normalized;
}

